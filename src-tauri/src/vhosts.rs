use std::{fs, io::Write, path::Path, process::{Command, Stdio}};

const ROOT: &str = "/srv/http";
const CONF: &str = "/etc/httpd/conf/extra/archagon-vhosts.conf";

fn safe_name(name: &str) -> bool {
    !name.is_empty() && name.len() <= 50 &&
    name.as_bytes()[0].is_ascii_alphanumeric() &&
    name.bytes().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
}

fn write_with_polkit(path: &str, content: &str) -> Result<(), String> {
    let mut child = Command::new("/usr/bin/pkexec")
        .args(["/usr/bin/tee", path])
        .stdin(Stdio::piped()).stdout(Stdio::null()).stderr(Stdio::piped())
        .spawn().map_err(|e| format!("Tidak bisa menjalankan pkexec: {e}"))?;
    child.stdin.take().ok_or("Gagal membuka stdin tee")?
        .write_all(content.as_bytes()).map_err(|e| e.to_string())?;
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    if out.status.success() { Ok(()) }
    else { Err(String::from_utf8_lossy(&out.stderr).trim().to_string()) }
}

#[tauri::command]
pub fn sync_vhosts() -> Result<String, String> {
    let root = Path::new(ROOT);
    if !root.is_dir() { return Err("Direktori /srv/http tidak ditemukan.".into()); }
    let mut projects: Vec<String> = fs::read_dir(root).map_err(|e| e.to_string())?
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().map(|t| t.is_dir()).unwrap_or(false))
        .filter_map(|entry| entry.file_name().into_string().ok())
        .filter(|name| safe_name(name))
        .collect();
    projects.sort();
    let mut conf = String::from("# Generated by Archagon. Do not edit manually.\n");
    for name in &projects {
        conf.push_str(&format!(
            "<VirtualHost *:80>\n    ServerName {0}.test\n    DocumentRoot \"/srv/http/{0}\"\n    <Directory \"/srv/http/{0}\">\n        AllowOverride All\n        Require all granted\n    </Directory>\n    ErrorLog \"/var/log/httpd/{0}-error.log\"\n    CustomLog \"/var/log/httpd/{0}-access.log\" combined\n</VirtualHost>\n\n", name
        ));
    }
    let current = fs::read_to_string(CONF).unwrap_or_default();
    if current != conf { write_with_polkit(CONF, &conf)?; }
    let hosts = fs::read_to_string("/etc/hosts").unwrap_or_default();
    let missing: Vec<&String> = projects.iter().filter(|name| {
        let expected = format!("127.0.0.1 {name}.test");
        !hosts.lines().any(|line| line.trim() == expected)
    }).collect();
    if !missing.is_empty() {
        let script = "from pathlib import Path\np=Path('/etc/hosts')\ns=p.read_text()\nfor name in __import__('sys').argv[1:]:\n line='127.0.0.1 '+name+'.test'\n if line not in s.splitlines(): s += ('\\n' if s and not s.endswith('\\n') else '')+line+'\\n'\np.write_text(s)";
        let mut cmd = Command::new("/usr/bin/pkexec");
        cmd.args(["/usr/bin/python3", "-c", script]);
        for name in missing { cmd.arg(name); }
        let output = cmd.output().map_err(|e| format!("Gagal memperbarui /etc/hosts: {e}"))?;
        if !output.status.success() {
            return Err(String::from_utf8_lossy(&output.stderr).trim().to_string());
        }
    }
    Ok(format!("Auto VHosts: {} project ditemukan. Konfigurasi ditulis ke {}.", projects.len(), CONF))
}
